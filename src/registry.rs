//! `spec-dna index <dir or file>` writes a generated index of the documents
//! of a directory: one table row for each entry document, with its name,
//! title and status. It replaces a large hand-kept registry file when the
//! entries exist as separate documents. The front matter field
//! `generated: spec-dna index h:<hash>` marks the file. `check` gives SD610
//! when the entries changed after the last run, or when the rows were edited
//! by hand.

use crate::hash::{hash_normalized, hex};
use crate::model::{Corpus, Doc, LinkRes};
use crate::mv::{parent, relative};

/// The value of the `generated` front matter field, before the hash.
pub const MARKER: &str = "spec-dna index";

/// One row of a generated index.
pub struct Entry {
    pub name: String,
    pub title: String,
    pub status: String,
    pub path: String,
}

/// The entry documents of the index at `index_path`: the documents under its
/// directory, without the index, stubs and other generated indexes, in the
/// natural order of their names.
pub fn entries(c: &Corpus, index_path: &str) -> Vec<Entry> {
    let id = c
        .by_path
        .get(index_path)
        .map(|&i| c.docs[i as usize].id.clone())
        .unwrap_or_default();
    entries_for(c, index_path, &id)
}

/// The entries of an index with the id `index_id`, also before the index
/// file exists.
pub fn entries_for(c: &Corpus, index_path: &str, index_id: &str) -> Vec<Entry> {
    let dir = parent(index_path);
    let index_id = Some(index_id).filter(|i| !i.is_empty());
    let mut out: Vec<Entry> = c
        .docs
        .iter()
        .filter(|d| {
            d.path != index_path
                && d.moved_to.is_none()
                && d.generated.is_none()
                && (dir.is_empty() || d.path.starts_with(&format!("{dir}/")))
        })
        .map(|d| Entry {
            name: name_of(d, index_id),
            title: d.parsed.title.replace('|', "\\|"),
            status: d.status.clone().unwrap_or_default(),
            path: d.path.clone(),
        })
        .collect();
    out.sort_by_key(|e| natural_key(&e.name));
    out
}

/// The name of an entry: its first legacy alias (such as `INC-12`), else its
/// id without the id of the index.
fn name_of(d: &Doc, index_id: Option<&str>) -> String {
    if let Some(a) = d.legacy_aliases.first() {
        return a.clone();
    }
    match index_id.and_then(|i| d.id.strip_prefix(&format!("{i}/"))) {
        Some(rest) => rest.to_string(),
        None => d.id.clone(),
    }
}

/// A sort key that orders the digit runs by number: `E-2` before `E-10`.
fn natural_key(s: &str) -> Vec<(u8, u64, String)> {
    let mut out = Vec::new();
    let mut rest = s;
    while !rest.is_empty() {
        let digits = rest.bytes().take_while(u8::is_ascii_digit).count();
        if digits > 0 {
            let n = rest[..digits].parse::<u64>().unwrap_or(u64::MAX);
            out.push((1, n, String::new()));
            rest = &rest[digits..];
        } else {
            let text = rest.bytes().take_while(|b| !b.is_ascii_digit()).count();
            out.push((0, 0, rest[..text].to_lowercase()));
            rest = &rest[text..];
        }
    }
    out
}

/// The hash of the entry list. The `generated` field records it.
pub fn hash(entries: &[Entry]) -> String {
    let text: String = entries
        .iter()
        .map(|e| format!("{}\t{}\t{}\t{}\n", e.name, e.title, e.status, e.path))
        .collect();
    hex(&hash_normalized(&text))
}

/// The full text of the generated index. It keeps the front matter fields of
/// `existing` (other than `generated`) and its title.
pub fn render(index_path: &str, entries: &[Entry], existing: Option<&str>, title: &str) -> String {
    let mut fm = String::new();
    if let Some(text) = existing
        && let Some((block, _)) = crate::frontmatter::split(text)
    {
        let mut skipping = false;
        for line in block.split_inclusive('\n') {
            let is_key = !line.starts_with([' ', '\t', '-']) && !line.trim().is_empty();
            if is_key {
                skipping = line.starts_with("generated:");
            }
            if !skipping {
                fm.push_str(line);
            }
        }
        if !fm.is_empty() && !fm.ends_with('\n') {
            fm.push('\n');
        }
    }
    fm.push_str(&format!("generated: {MARKER} h:{}\n", hash(entries)));
    let dir = parent(index_path);
    let mut out = format!(
        "---\n{fm}---\n# {title}\n\n<!-- Generated by `spec-dna index {index_path}`. Do not edit by hand. -->\n\n| Entry | Title | Status |\n| --- | --- | --- |\n"
    );
    for e in entries {
        out.push_str(&format!(
            "| [{}]({}) | {} | {} |\n",
            e.name,
            relative(dir, &e.path),
            e.title,
            e.status
        ));
    }
    out
}

/// The new destination of a link from the document at `from` to a section of
/// the old index file: the entry whose name gives the anchor, such as
/// `#inc-12` or `#inc-12-cache-outage` for `INC-12`. `None` keeps the link.
pub fn entry_link(
    c: &Corpus,
    from: &str,
    dest: &str,
    index_path: &str,
    entries: &[Entry],
) -> Option<String> {
    let (path, frag) = dest.split_once('#')?;
    if path.is_empty() {
        return None;
    }
    match c.resolve_link(from, dest) {
        LinkRes::File(p, _, _) if p == index_path => {}
        _ => return None,
    }
    let frag = frag.to_lowercase();
    let e = entries.iter().find(|e| {
        let slug = crate::parse::slugify(&e.name);
        !slug.is_empty() && (frag == slug || frag.starts_with(&format!("{slug}-")))
    })?;
    let _ = path;
    Some(relative(parent(from), &e.path))
}

/// Returns the reason why a generated index is stale, or `None`.
pub fn stale(c: &Corpus, doc: u32) -> Option<String> {
    let d = &c.docs[doc as usize];
    let recorded = d.generated.as_deref()?;
    let want = entries(c, &d.path);
    let mut linked: Vec<String> = d
        .parsed
        .refs
        .iter()
        .filter_map(|r| match c.resolve_link(&d.path, &r.target) {
            LinkRes::File(p, Some(_), _) => Some(p),
            _ => None,
        })
        .collect();
    linked.sort();
    linked.dedup();
    let mut paths: Vec<String> = want.iter().map(|e| e.path.clone()).collect();
    paths.sort();
    let now = hash(&want);
    let field = recorded.strip_prefix("h:").unwrap_or(recorded);
    if field != now {
        let gone = linked.iter().filter(|p| !paths.contains(p)).count();
        let added = paths.iter().filter(|p| !linked.contains(p)).count();
        return Some(format!(
            "the generated index is stale: the entries changed after the last `spec-dna index` ({} entries now, {added} new, {gone} gone, or a title or status changed)",
            want.len()
        ));
    }
    if linked != paths {
        return Some("the rows of the generated index were edited by hand".to_string());
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_sort_by_number() {
        let mut v = vec!["E-10", "E-2", "E-1", "a"];
        v.sort_by_key(|s| natural_key(s));
        assert_eq!(v, ["a", "E-1", "E-2", "E-10"]);
    }
}
